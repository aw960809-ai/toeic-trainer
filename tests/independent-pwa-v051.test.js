'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const Auto=require('../js/auto-sync.js');
const manifest=JSON.parse(fs.readFileSync(path.join(root,'manifest.webmanifest'),'utf8'));
const mainScope='/my-goal-manager/', trainerScope='/toeic-trainer/';
assert.equal(manifest.id,trainerScope);
assert.equal(manifest.start_url,trainerScope);
assert.equal(manifest.scope,trainerScope);
assert.equal(trainerScope.startsWith(mainScope),false);
assert.equal(mainScope.startsWith(trainerScope),false);
assert.equal(Auto.hosted({protocol:'https:',pathname:'/toeic-trainer/',href:'https://aw960809-ai.github.io/toeic-trainer/'}),true);
assert.equal(Auto.hosted({protocol:'https:',pathname:'/my-goal-manager/apps/toeic-trainer/',href:'https://aw960809-ai.github.io/my-goal-manager/apps/toeic-trainer/'}),false);
assert.equal(Auto.hosted({protocol:'http:',pathname:'/toeic-trainer/',href:'http://localhost/toeic-trainer/'}),false);
assert.equal(Auto.hosted({protocol:'https:',pathname:'/toeic-trainer/',href:'https://random.example/toeic-trainer/'}),false);
assert.equal(Auto.KEY,'toeic-trainer:v051-link-settings');
assert.equal(require('../js/core.js').KEY,'toeic-trainer-v01:learning-state','historical session/SRS key must not change');
const legacyKey='toeic-trainer:v05-link-settings';
const storeData=new Map([[legacyKey,JSON.stringify({version:1,enabled:true,enabledAt:'2026-10-12T00:00:00Z'})]]);
const store={getItem:k=>storeData.get(k)||null,setItem:(k,v)=>storeData.set(k,v)};
assert.equal(Auto.read(store),null,'previous embedded-app consent must NOT auto-enable');
const t=new Date('2026-10-12T10:00:00Z');
assert.equal(Auto.enable(store,{location:{protocol:'https:',pathname:'/toeic-trainer/',href:'https://aw960809-ai.github.io/toeic-trainer/'},now:t}).enabledAt,t.toISOString());
assert(storeData.has(legacyKey),'no deletion or overwrite of historical consent');
const sw=fs.readFileSync(path.join(root,'sw.js'),'utf8');
assert(sw.includes('toeic-trainer-independent-v0.5.1'));
assert(sw.includes("const OWN_PREFIX='toeic-trainer-independent-'"),'must not delete legacy PWA cache');
const workflow=fs.readFileSync(path.join(root,'.github/workflows/pages.yml'),'utf8');
assert(workflow.includes('npm test')&&workflow.includes('actions/deploy-pages@v4'));
console.log('PASS: independent manifest ID/scope, URL routing, one-time opt-in, old storage/SRS preserved, SW isolated');
